import assert from 'node:assert'
import { SWITCH_GROUPS, GROUP_ORDER, groupIds, switchIds, advancedCount, classifySwitch, hasChildren, visualWrites, visualReads, FEATURE_SWITCHES, FEATURE_ORDER, featureAbsorbed, featureAbsorbedAll, featureState, featureWrites, featureLabel, compatEmpathy,
         groupState, expandGroup, groupRowText, normalizeViewMode, VIEW_STORAGE_KEY, TAB_GROUPS, TAB_ORDER,
         tabOfSwitch, visibleElements, TAB_CONTENT, tabContentCount, visibleInteractive } from '../switch_groups.mjs'

assert.deepEqual(groupIds(), ['memory', 'expression', 'llm', 'safety', 'visual', 'system'])
assert.equal(advancedCount(), 27)
const ids = switchIds()
assert.equal(new Set(ids).size, 27)  // no duplicate / full coverage after visual dedupe
for (const id of ids) assert.notEqual(classifySwitch(id), '')
assert.equal(classifySwitch('unknown_switch'), '')
assert.equal(SWITCH_GROUPS.memory.ids.length, 12)
assert.equal(SWITCH_GROUPS.expression.ids.length, 4)
assert.equal(SWITCH_GROUPS.llm.ids.length, 1)
assert.equal(SWITCH_GROUPS.safety.ids.length, 1)
assert.equal(SWITCH_GROUPS.visual.ids.length, 9)
assert.equal(hasChildren('system'), false)
assert.equal(hasChildren('visual'), true)

assert.equal(groupState('visual', {}), 'off')
assert.equal(groupState('visual', Object.fromEntries(SWITCH_GROUPS.visual.ids.map((id) => [id, true]))), 'on')
assert.equal(groupState('visual', { swShowNoise: true }), 'mixed')
assert.equal(groupState('safety', { swSafetyEnabled: true }), 'on')
assert.equal(groupState('system', {}), 'off')

const allOn = expandGroup('memory', true)
assert.equal(Object.values(allOn).filter((value) => value === true).length, 12)
const allOff = expandGroup('memory', false)
assert.equal(Object.values(allOff).filter((value) => value === false).length, 12)
assert.equal(expandGroup('system', true).constructor, Object)

assert.ok(groupRowText('memory').includes('12 项'))
assert.ok(groupRowText('llm').includes('候选'))
assert.ok(groupRowText('system').includes('操作按钮'))
assert.equal(normalizeViewMode(undefined), 'simple')
assert.equal(normalizeViewMode('advanced'), 'advanced')
assert.equal(normalizeViewMode('bogus'), 'simple')
assert.equal(VIEW_STORAGE_KEY, 'biocore_settings_view')
assert.deepEqual(TAB_ORDER, ['api', 'coreStatus', 'safety', 'llm', 'expression', 'memory', 'visual', 'version', 'backup', 'persona'])
assert.equal(TAB_GROUPS.coreStatus.length, 0)  // status tab holds no group switches
assert.ok(TAB_ORDER.length === 10 && !TAB_ORDER.includes('coreMode'))
for (const tab of ['coreStatus', 'safety', 'llm']) assert.ok(tabContentCount(tab) > 0, tab)
for (const id of switchIds()) {
  const tab = tabOfSwitch(id)
  assert.notEqual(tab, '')
  assert.notEqual(tab, 'coreStatus')
}
assert.equal(tabOfSwitch('swSafetyEnabled'), 'safety')
assert.equal(tabOfSwitch('fn_empathy_hint_enabled'), 'expression')
assert.equal(tabOfSwitch('swShowNoise'), 'visual')
assert.equal(tabOfSwitch('swLlmCandidates'), 'llm')
assert.equal(tabOfSwitch('swLlmCandidates'), 'llm')
assert.equal(TAB_GROUPS.persona.length, 0)
assert.equal(tabOfSwitch('swCompress'), 'memory')
const simple = visibleElements('simple')
const advanced = visibleElements('advanced')
assert.equal(simple.switches, 0)
assert.equal(advanced.switches, 27)
assert.ok(advanced.total > simple.total)
assert.equal(simple.groups, 6)
assert.equal(advanced.diagnostics, 1)
const simpleInteractive = visibleInteractive('simple')
const advancedInteractive = visibleInteractive('advanced')
assert.ok(simpleInteractive.total <= 12, String(simpleInteractive.total))
assert.equal(advancedInteractive.individual, 27)
assert.equal(advancedInteractive.individual + advancedInteractive.groups, 33)
assert.deepEqual(visualWrites('swShowMemoryNodes', true), { bio_show_memory_nodes: '1', bio_show_nodes: '1' })
assert.deepEqual(visualWrites('swShowLinks', false), { bio_show_links: '0', bio_show_node_links: '0' })
assert.deepEqual(visualWrites('swShowEcho', true), { bio_show_echo: '1', bio_show_ripple: '1' })
assert.equal(visualReads('swShowLinks', { bio_show_links: '0', bio_show_node_links: '1' }), true)  // either true => on
assert.equal(visualReads('swShowEcho', { bio_show_echo: '0', bio_show_ripple: '0' }), false)
assert.equal(visualReads('swMemoryBallsImportant', {}), undefined)
assert.equal(FEATURE_ORDER.length, 11)
assert.equal(FEATURE_ORDER.length, 11)
const absorbed = featureAbsorbedAll()
assert.equal(new Set(absorbed).size, absorbed.length)  // absorbedUnique=20: 11 功能开关吸收的旧键去重后
assert.ok(absorbed.every((id) => switchIds().includes(id)), 'absorbed ids must be real switches')
assert.equal(switchIds().length - absorbed.length, 8)  // switchIds=27（页面独立开关）− absorbedUnique=19 = 8 个仅高级项（情绪强度环独立）
assert.deepEqual(featureWrites('feat_visual_nodes', true), { swShowMemoryNodes: true })
