assert.ok(featureLabel('feat_llm_image').includes('[LLM]'))
assert.ok(!featureLabel('feat_compress').includes('[LLM]'))
assert.equal(featureAbsorbed('feat_expression_rules').length, 1)
assert.deepEqual(featureAbsorbed('feat_visual_rings'), ['swShowEcho','swShowDominance','swShowSocial'])
